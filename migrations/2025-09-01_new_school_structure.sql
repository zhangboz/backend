-- Wrap the entire schema migration in a single transaction.
BEGIN;

-- 1. DROP EXISTING OBJECTS (in the correct dependency order)
DROP TABLE IF EXISTS chunks;
DROP TABLE IF EXISTS documents;
DROP TABLE IF EXISTS course_instructors;
DROP TABLE IF EXISTS course_offerings;
DROP TABLE IF EXISTS courses;
DROP TABLE IF EXISTS professors;
DROP TABLE IF EXISTS departments;
DROP TABLE IF EXISTS institutions;
DROP TYPE IF EXISTS SEMESTER_TYPE;


-- 2. CREATE CUSTOM TYPES
CREATE TYPE SEMESTER_TYPE AS ENUM ('Fall', 'Winter', 'Spring', 'Summer');


-- 3. CREATE TABLES WITH LOOSER MVP RULES

-- Table: institutions
-- MODIFIED: Added 'short_name' as the key identifier. 'name' and 'country' are now optional.
CREATE TABLE institutions (
    institution_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) UNIQUE,
    short_name VARCHAR(30) NOT NULL UNIQUE, -- Now the required, unique identifier (e.g., 'UBC').
    city VARCHAR(100),
    state_province VARCHAR(100),
    country VARCHAR(100) -- No longer NOT NULL
);

-- Table: departments
-- This remains unchanged as the link to an institution and the department name are essential.
CREATE TABLE departments (
    department_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    institution_id INT NOT NULL,
    CONSTRAINT uq_department_name_institution UNIQUE (name, institution_id),
    CONSTRAINT fk_department_institution
      FOREIGN KEY(institution_id) REFERENCES institutions(institution_id) ON DELETE RESTRICT
);

-- Table: professors
-- MODIFIED: Only 'last_name' is required. First name and email are optional.
CREATE TABLE professors (
    professor_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name VARCHAR(100), -- No longer NOT NULL
    last_name VARCHAR(100) NOT NULL,
    email VARCHAR(255) UNIQUE, -- No longer NOT NULL, but remains UNIQUE if provided
    title VARCHAR(100),
    department_id INT NOT NULL,
    CONSTRAINT fk_professor_department
      FOREIGN KEY(department_id) REFERENCES departments(department_id) ON DELETE RESTRICT
);

-- Table: courses
-- MODIFIED: Only 'course_code' is required. Name and credits are optional.
CREATE TABLE courses (
    course_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_code VARCHAR(20) NOT NULL,
    course_name VARCHAR(255), -- No longer NOT NULL
    description TEXT,
    credits NUMERIC(3, 1), -- No longer NOT NULL
    department_id INT NOT NULL,
    CONSTRAINT uq_course_code_department UNIQUE (course_code, department_id),
    CONSTRAINT fk_course_department
      FOREIGN KEY(department_id) REFERENCES departments(department_id) ON DELETE RESTRICT
);

-- Table: course_offerings
-- This remains unchanged, as a specific "offering" requires a course, year, and semester to be meaningful.
CREATE TABLE course_offerings (
    offering_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id INT NOT NULL,
    year INT NOT NULL,
    semester SEMESTER_TYPE NOT NULL,
    CONSTRAINT uq_course_offering UNIQUE (course_id, year, semester),
    CONSTRAINT fk_offering_course
      FOREIGN KEY(course_id) REFERENCES courses(course_id) ON DELETE CASCADE
);

-- Table: course_instructors
CREATE TABLE course_instructors (
    course_offering_id INT NOT NULL,
    professor_id INT NOT NULL,
    PRIMARY KEY (course_offering_id, professor_id),
    CONSTRAINT fk_instructor_offering
      FOREIGN KEY(course_offering_id) REFERENCES course_offerings(offering_id) ON DELETE CASCADE,
    CONSTRAINT fk_instructor_professor
      FOREIGN KEY(professor_id) REFERENCES professors(professor_id) ON DELETE CASCADE
);

-- Table: documents
CREATE TABLE documents (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    file_url TEXT NOT NULL,
    file_name TEXT NOT NULL,
    mime_type TEXT,
    file_size INT,
    document_type TEXT,
    transcribed_text TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    course_offering_id INT NULL,
    CONSTRAINT fk_document_offering
      FOREIGN KEY(course_offering_id) REFERENCES course_offerings(offering_id) ON DELETE SET NULL
);

-- Table: chunks
CREATE TABLE chunks (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id INT NOT NULL,
    chunk_id INT,
    text TEXT,
    summary TEXT,
    start_pos INT,
    chunk_length INT,
    embedding vector(768),
    created_at TIMESTAMPTZ DEFAULT NOW(),
    CONSTRAINT fk_chunk_document
      FOREIGN KEY(document_id) REFERENCES documents(id) ON DELETE CASCADE
);


-- 4. ADD INDEXES
CREATE INDEX idx_documents_course_offering_id ON documents(course_offering_id);
CREATE INDEX idx_chunks_document_id ON chunks(document_id);


-- Finally, commit the transaction.
COMMIT;